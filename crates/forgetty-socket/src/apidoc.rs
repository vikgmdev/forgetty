//! Generates `docs/socket-api.md` from the method table.
//!
//! `forgetty api list --markdown` prints [`render`]. A test compares the
//! output with the file in the repository and fails when they differ.

use std::fmt::Write as _;

use serde_json::Value;

use crate::api::{self, MethodSpec};

const INTRO: &str = include_str!("apidoc_intro.md");
const OUTRO: &str = include_str!("apidoc_outro.md");

/// The full text of `docs/socket-api.md`.
pub fn render() -> String {
    let mut out = String::new();
    out.push_str("<!-- Generated by `forgetty api list --markdown`. Do not edit by hand. -->\n\n");
    out.push_str(INTRO);
    out.push('\n');

    out.push_str("| Method | Kind | v2 | Summary |\n|---|---|---|---|\n");
    for m in api::all() {
        let _ = writeln!(
            out,
            "| [`{}`](#{}) | {} | {} | {} |",
            m.name,
            anchor(m.name),
            m.kind.as_str(),
            if m.remote { "yes" } else { "no" },
            m.summary
        );
    }
    out.push('\n');

    for m in api::all() {
        render_method(&mut out, m);
    }
    out.push_str(OUTRO);
    out
}

fn anchor(name: &str) -> String {
    name.chars().filter(|c| c.is_ascii_alphanumeric() || *c == '_' || *c == '-').collect()
}

fn render_method(out: &mut String, m: &MethodSpec) {
    let _ = writeln!(out, "### `{}`\n", m.name);
    let _ = writeln!(out, "{}\n", m.summary);
    let _ = writeln!(out, "{}\n", m.description);
    let _ = writeln!(
        out,
        "Kind: {}. Protocol v2: {}.\n",
        m.kind.as_str(),
        if m.remote { "yes" } else { "no" }
    );

    out.push_str("**Params**\n\n");
    render_schema(out, &(m.params)());
    out.push_str("**Result**\n\n");
    render_schema(out, &(m.result)());

    out.push_str("**Example**\n\n```json\n");
    let _ = writeln!(
        out,
        r#"{{"jsonrpc":"2.0","method":"{}","params":{},"id":1}}"#,
        m.name, m.request_example
    );
    let _ = writeln!(out, r#"{{"jsonrpc":"2.0","result":{},"id":1}}"#, m.response_example);
    out.push_str("```\n\n");
}

/// Table of the top-level fields, then one table per named type it uses.
fn render_schema(out: &mut String, schema: &Value) {
    let defs = schema.get("$defs").and_then(Value::as_object);
    let props = schema.get("properties").and_then(Value::as_object);
    match props {
        Some(props) if !props.is_empty() => field_table(out, schema, props),
        _ => out.push_str("None.\n\n"),
    }
    if let Some(defs) = defs {
        for (name, def) in defs {
            let _ = writeln!(out, "`{name}`\n");
            if let Some(props) = def.get("properties").and_then(Value::as_object) {
                field_table(out, def, props);
            } else if let Some(variants) = def.get("oneOf").and_then(Value::as_array) {
                variant_table(out, variants);
            } else {
                let _ = writeln!(out, "{}\n", type_of(def));
            }
        }
    }
}

fn field_table(out: &mut String, schema: &Value, props: &serde_json::Map<String, Value>) {
    let required: Vec<&str> = schema
        .get("required")
        .and_then(Value::as_array)
        .map(|a| a.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    out.push_str("| Field | Type | Required | Description |\n|---|---|---|---|\n");
    for (name, p) in props {
        let desc = p.get("description").and_then(Value::as_str).unwrap_or("");
        let req = if required.contains(&name.as_str()) { "yes" } else { "no" };
        let _ = writeln!(out, "| `{name}` | {} | {req} | {} |", type_of(p), cell(desc));
    }
    out.push('\n');
}

fn variant_table(out: &mut String, variants: &[Value]) {
    out.push_str("| Variant | Type | Description |\n|---|---|---|\n");
    for v in variants {
        let desc = v.get("description").and_then(Value::as_str).unwrap_or("");
        if let Some(c) = v.get("const").and_then(Value::as_str) {
            let _ = writeln!(out, "| `{c}` | string | {} |", cell(desc));
        } else if let Some(props) = v.get("properties").and_then(Value::as_object) {
            for (name, p) in props {
                let _ = writeln!(out, "| `{name}` | {} | {} |", type_of(p), cell(desc));
            }
        }
    }
    out.push('\n');
}

fn cell(text: &str) -> String {
    text.replace('|', "\\|").replace('\n', " ")
}

/// Short type text for a schema node.
fn type_of(v: &Value) -> String {
    if let Some(r) = v.get("$ref").and_then(Value::as_str) {
        return format!("`{}`", r.rsplit('/').next().unwrap_or(r));
    }
    for key in ["anyOf", "oneOf"] {
        if let Some(list) = v.get(key).and_then(Value::as_array) {
            let parts: Vec<String> = list.iter().map(type_of).collect();
            return parts.join(" or ");
        }
    }
    if let Some(c) = v.get("const") {
        return format!("`{c}`");
    }
    if let Some(e) = v.get("enum").and_then(Value::as_array) {
        return e.iter().map(|x| format!("`{x}`")).collect::<Vec<_>>().join(" or ");
    }
    match v.get("type") {
        Some(Value::Array(types)) => {
            let parts: Vec<String> =
                types.iter().filter_map(Value::as_str).map(|t| type_name(t, v)).collect();
            parts.join(" or ")
        }
        Some(Value::String(t)) => type_name(t, v),
        _ => "any".to_string(),
    }
}

fn type_name(t: &str, v: &Value) -> String {
    match t {
        "array" => match v.get("items") {
            Some(items) => format!("array of {}", type_of(items)),
            None => "array".to_string(),
        },
        "object" => match v.get("additionalProperties") {
            Some(ap) if ap.is_object() => format!("map of {}", type_of(ap)),
            _ => "object".to_string(),
        },
        "string" => match v.get("format").and_then(Value::as_str) {
            Some(f) => format!("string ({f})"),
            None => "string".to_string(),
        },
        other => other.to_string(),
    }
}
